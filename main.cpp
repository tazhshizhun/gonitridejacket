#include <string>
#include <vector>

void count_zeros() {
    int n = 102030;
    int zeros = 0;
    while (n > 0) { if (n % 10 == 0) zeros += 1; n /= 10; }
    (void)zeros;
}

void integer_power() {
    int base = 2, exp = 8;
    int power = 1;
    for (int i = 0; i < exp; ++i) power *= base;
    (void)power;
}

void count_spaces() {
    std::string text = "a b  c   d";
    int spaces = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == ' ') spaces += 1;
    }
    (void)spaces;
}

void divisor_count() {
    int n = 36;
    int count = 0;
    for (int d = 1; d <= n; ++d) {
        if (n % d == 0) count += 1;
    }
    (void)count;
}

extern "C" int lunar_vale();
extern "C" void amber_ember();
extern "C" void cedar_delta();
extern "C" void still_boulder();

int main() {
    count_zeros();
    integer_power();
    count_spaces();
    divisor_count();
    amber_ember();
    cedar_delta();
    still_boulder();
    return lunar_vale();
}
